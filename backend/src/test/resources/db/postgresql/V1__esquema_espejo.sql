-- Esquema espejo de SIATE (Oracle, esquema SIANTE) para PostgreSQL, sin PostGIS.
-- Generado desde siate_.csv (diccionario de columnas de Oracle): 18 tablas, 107 columnas.
-- Omitidas: MDRT_B4C74$ (índice espacial interno de Oracle).
-- Espejo fiel a Oracle para la carga inicial y la réplica: mismos nombres, largos, nulabilidad y claves.
-- Las mejoras (jsonb, códigos numéricos, FK faltantes) van aparte; ver docs/modelo-datos.md.
-- Sin LAYERS_FEATURES.SPATIAL_OBJECT (SDO_GEOMETRY): por ahora no se usa PostGIS y la geometría de cada elemento
-- está como GeoJSON en JSON_METADATA, que es de donde la lee siante2.

create table categories (
    id                 integer generated by default as identity not null,
    name               varchar(50),
    description        varchar(200),
    status             varchar(20),
    constraint categories_pk primary key (id)
);

create table favorites (
    user_id            integer not null,
    l_group_id         integer not null,
    created_date       timestamp(0),
    constraint favorites_pk primary key (user_id, l_group_id)
);

create table layers (
    id                 integer generated by default as identity not null,
    owner              integer,
    name               varchar(200),
    origin             varchar(20),
    status             varchar(20),
    description        varchar(1000),
    visibility         varchar(20),
    l_group_id         integer,
    json_metadata      text,
    category_id        integer,
    created_date       timestamp(0) default localtimestamp(0),
    file_base64        text,
    constraint layers_pk primary key (id)
);

create table layers_categories (
    layer_id           integer not null,
    category_id        integer not null,
    constraint layers_categories_pk primary key (layer_id, category_id)
);

create table layers_features (
    id_feature         integer not null,
    id_layer           integer not null,
    type               varchar(20) not null,
    date_create        timestamp(0) default localtimestamp(0),
    date_modify        timestamp(0) default localtimestamp(0),
    json_metadata      text,
    constraint layers_features_pk primary key (id_feature, id_layer)
);

create table layers_groups (
    id                 integer generated by default as identity not null,
    name               varchar(200),
    description        varchar(1000),
    owner              integer,
    status             integer,
    created_date       timestamp(0),
    is_scheduler       integer,
    create_type        varchar(20),
    constraint layers_groups_pk primary key (id)
);

create table layers_groups_layers (
    layer_id           integer not null,
    l_group_id         integer not null,
    created_date       timestamp(0),
    constraint layers_groups_layers_pk primary key (layer_id, l_group_id)
);

create table layers_users_groups (
    l_group_id         integer not null,
    u_group_id         integer not null,
    created_date       timestamp(0),
    constraint layers_users_groups_pk primary key (l_group_id, u_group_id)
);

create table multimedia (
    creado             varchar(20),
    f_creacion         timestamp(0),
    modificado         varchar(20),
    f_modificacion     timestamp(0),
    descripcion        varchar(20),
    x_multimedia       integer generated by default as identity not null,
    archivo            bytea,
    constraint multimedia_pk primary key (x_multimedia)
);

create table parametros (
    nombre             varchar(250),
    valor              varchar(250),
    estado             smallint
);

create table points_catalog (
    id                 integer generated by default as identity not null,
    name               varchar(200),
    url                text,
    name_file          text,
    visibility         varchar(20),
    owner              integer,
    name_image         varchar(200),
    constraint points_catalog_pk primary key (id)
);

create table public_reports (
    creado             integer,
    f_creacion         timestamp(0),
    x_pure             integer generated by default as identity not null,
    version            integer,
    layer_id           integer,
    qr                 varchar(400),
    layers_groups_id   integer,
    name               varchar(400),
    json_metadata      text,
    descripcion        varchar(400),
    constraint public_reports_pk primary key (x_pure)
);

create table public_reports_details (
    creado             integer,
    f_creacion         timestamp(0),
    x_puredet          integer generated by default as identity not null,
    pure_x_pure        integer,
    layer_id           integer,
    version            integer,
    qr                 varchar(400),
    name               varchar(400),
    json_metadata      text,
    constraint public_reports_details_pk primary key (x_puredet)
);

create table public_reports_temporal (
    creado             integer,
    f_creacion         timestamp(0),
    x_pure_temporal    integer generated by default as identity not null,
    version            integer,
    layer_id           integer,
    qr                 varchar(400),
    layers_groups_id   integer,
    name               varchar(400),
    json_metadata      text,
    descripcion        varchar(400),
    constraint public_reports_temporal_pk primary key (x_pure_temporal)
);

create table scheduler_data (
    id                 integer generated by default as identity not null,
    data               text,
    layer_id           integer,
    status             varchar(20),
    l_group_id         integer,
    constraint scheduler_data_pk primary key (id)
);

create table users (
    id                 integer generated by default as identity not null,
    name               varchar(50),
    last_name          varchar(50),
    email              varchar(100),
    area               varchar(50),
    iv_user            varchar(20),
    iv_group           varchar(1000),
    superuser          varchar(20),
    constraint users_pk primary key (id)
);

create table users_groups (
    id                 integer generated by default as identity not null,
    owner              integer not null,
    name               varchar(50),
    description        varchar(200),
    constraint users_groups_pk primary key (id)
);

create table users_groups_users (
    user_id            integer not null,
    u_group_id         integer not null,
    constraint users_groups_users_pk primary key (user_id, u_group_id)
);

