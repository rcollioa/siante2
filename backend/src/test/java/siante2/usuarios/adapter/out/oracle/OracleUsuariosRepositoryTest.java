package siante2.usuarios.adapter.out.oracle;

import jakarta.persistence.EntityManagerFactory;
import java.util.List;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.data.jpa.test.autoconfigure.DataJpaTest;
import org.springframework.jdbc.core.JdbcTemplate;
import siante2.ContadorSql;
import siante2.usuarios.domain.Usuario;

import static org.assertj.core.api.Assertions.assertThat;

/** {@code USERS} con ID autogenerado, como en Oracle (la entidad no lo genera). */
@DataJpaTest
class OracleUsuariosRepositoryTest {

    @Autowired
    private UsuarioJpaRepository jpa;

    @Autowired
    private JdbcTemplate jdbc;

    @Autowired
    private EntityManagerFactory fabrica;

    private OracleUsuariosRepository repositorio;

    @BeforeEach
    void preparar() {
        jdbc.execute("drop table if exists USERS");
        jdbc.execute("create table USERS (ID integer generated by default as identity primary key, NAME varchar(100),"
                + " LAST_NAME varchar(100), EMAIL varchar(100), AREA varchar(100), IV_USER varchar(100),"
                + " IV_GROUP varchar(400))");
        repositorio = new OracleUsuariosRepository(jpa);
    }

    @Test
    void registraConLasColumnasDeSianteYLoEncuentraPorIvUser() {
        repositorio.registrar("jperez", List.of("SIATE", "CGR"));

        Usuario usuario = repositorio.buscarPorIvUser("jperez", List.of("SIATE")).orElseThrow();

        assertThat(usuario.nombre()).isEqualTo("jperez");
        assertThat(usuario.apellido()).isEmpty();
        assertThat(usuario.email()).isEmpty();
        assertThat(jdbc.queryForObject("select IV_GROUP from USERS where IV_USER = 'jperez'", String.class))
                .isEqualTo("SIATE,CGR");
    }

    @Test
    void conDuplicadosTomaElDeMenorIdEnUnaSolaConsulta() {
        jdbc.update("insert into USERS (ID, NAME, IV_USER) values (7, 'Segundo', 'dup')");
        jdbc.update("insert into USERS (ID, NAME, IV_USER) values (3, 'Primero', 'dup')");

        ContadorSql sql = new ContadorSql(fabrica);

        assertThat(repositorio.buscarPorIvUser("dup", List.of()).orElseThrow().id()).isEqualTo(3);
        assertThat(sql.sentencias()).isEqualTo(1);
    }
}
